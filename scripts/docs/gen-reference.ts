/**
 * Generates the machine-readable reference the public doc site consumes:
 *
 *   docs/reference/mcp-tools.json + .md   the pod's MCP tools
 *   docs/reference/events.json + .md      the event catalog and naming grammar
 *   docs/reference/hub-openapi.json       the Hub Protocol REST OpenAPI 3.1 spec
 *
 * Run from the repo root (workspace dependencies must be built first, the same
 * set CI builds in .github/actions/monorepo-setup):
 *
 *   pnpm docs:reference           write the files
 *   pnpm docs:reference:check     exit 1 when a committed file is stale
 *
 * Every field is read from the running source, never parsed out of text:
 *   - MCP tools: `tools.list()` with no context (the same call
 *     packages/api/src/routers/mcp/tools/gen-manifest.ts serializes), plus the
 *     listing group of each tool from routers/mcp/tool-profiles.ts.
 *   - Events: `OperationalEventTypes` / `SystemEventTypes` from
 *     packages/events/src/event-types.ts, and the naming grammar constants from
 *     packages/types/src/events/unified.ts.
 *   - OpenAPI: the document `GET /api/hub/openapi.json` serves, produced by
 *     requesting that route on the imported Hono app (no server, no database:
 *     the pool connects lazily and nothing here queries it).
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const OUT_DIR = resolve(ROOT, "docs/reference");
const CHECK = process.argv.includes("--check");

// Importing the API boots its config module, which requires a DATABASE_URL.
// Nothing below opens a connection; a placeholder that cannot connect makes
// that explicit instead of borrowing whatever database the caller has.
process.env.DATABASE_URL ??= "postgresql://docs:docs@127.0.0.1:1/docs";
process.env.NODE_ENV ??= "test";
process.env.LOG_LEVEL ??= "error";

const GENERATED_BY =
  "Generated by scripts/docs/gen-reference.ts. Do not edit; run `pnpm docs:reference`.";

// ── helpers ─────────────────────────────────────────────────────────────────

type JsonSchema = {
  type?: string | string[];
  description?: string;
  enum?: unknown[];
  items?: JsonSchema;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  default?: unknown;
  [k: string]: unknown;
};

function schemaType(s: JsonSchema | undefined): string {
  if (!s) return "";
  if (s.enum) return "enum";
  const alts = s.anyOf ?? s.oneOf;
  if (alts) return alts.map(schemaType).filter(Boolean).join(" | ");
  const t = Array.isArray(s.type) ? s.type.join(" | ") : (s.type ?? "");
  if (t === "array" && s.items) return `array<${schemaType(s.items) || "any"}>`;
  return t;
}

function cell(s: unknown): string {
  return String(s ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\r?\n+/g, " ")
    .trim();
}

async function formatted(file: string, content: string): Promise<string> {
  const config = (await prettier.resolveConfig(file)) ?? {};
  return prettier.format(content, { ...config, filepath: file });
}

const outputs: Array<{ file: string; content: string }> = [];
async function emit(name: string, content: string) {
  const file = resolve(OUT_DIR, name);
  outputs.push({ file, content: await formatted(file, content) });
}

// ── MCP tools ───────────────────────────────────────────────────────────────

async function mcpTools() {
  const { tools } =
    await import("../../packages/api/src/routers/mcp/tools/index.js");
  const { ENTRY_TOOLS, TOOL_GROUPS } =
    await import("../../packages/api/src/routers/mcp/tool-profiles.js");
  const defs = (await tools.list()) as Array<{
    name: string;
    title?: string;
    description?: string;
    annotations?: Record<string, unknown>;
    inputSchema: JsonSchema;
  }>;

  const groupOf = new Map<string, string>();
  for (const name of ENTRY_TOOLS as readonly string[])
    groupOf.set(name, "entry");
  for (const [group, names] of Object.entries(
    TOOL_GROUPS as Record<string, readonly string[]>
  ))
    for (const name of names) groupOf.set(name, group);

  const entries = defs.map((t) => {
    const props = t.inputSchema?.properties ?? {};
    const required = new Set(t.inputSchema?.required ?? []);
    return {
      name: t.name,
      title: (t.annotations?.title as string | undefined) ?? t.title,
      group: groupOf.get(t.name) ?? null,
      annotations: t.annotations ?? {},
      description: t.description ?? "",
      parameters: Object.entries(props).map(([name, s]) => ({
        name,
        type: schemaType(s),
        required: required.has(name),
        description: s.description,
        enum: s.enum,
      })),
      inputSchema: t.inputSchema,
    };
  });

  const json = {
    $comment: GENERATED_BY,
    source: [
      "packages/api/src/routers/mcp/tools/index.ts (tools.list(), no context)",
      "packages/api/src/routers/mcp/tool-profiles.ts (ENTRY_TOOLS, TOOL_GROUPS)",
    ],
    notes: {
      group:
        "Which listing group the tool belongs to: 'entry' tools are listed to every key; other groups are listed to an entry-profile key once unlocked with synap_load_skill('tools:<group>'). A group narrows listing only and is not a permission.",
      scopes:
        "Tool definitions declare no required API key scopes. Scope checks (mcp.read / mcp.write) run inside the handlers when a tool is called.",
    },
    toolCount: entries.length,
    entryTools: ENTRY_TOOLS,
    groups: TOOL_GROUPS,
    tools: entries,
  };
  await emit("mcp-tools.json", JSON.stringify(json));

  const md: string[] = [
    `<!-- ${GENERATED_BY} -->`,
    "",
    "# MCP tools",
    "",
    `The pod's MCP server lists ${entries.length} tools. A new agent key lists the \`entry\` tools; the others arrive by group when an agent calls \`synap_load_skill\` with \`tools:<group>\` (or \`tools:builder\` for every group). A group narrows what is listed; it is not a permission. A call still runs under the key's scopes and the pod's governance.`,
    "",
    "| Tool | Title | Group | Read-only |",
    "| --- | --- | --- | --- |",
    ...entries.map(
      (t) =>
        `| [\`${t.name}\`](#${t.name}) | ${cell(t.title)} | ${t.group ?? ""} | ${t.annotations.readOnlyHint === true ? "yes" : t.annotations.readOnlyHint === false ? "no" : ""} |`
    ),
    "",
  ];
  for (const t of entries) {
    md.push(`## ${t.name}`, "");
    const facts = [
      t.title ? `**${t.title}**` : "",
      t.group ? `Group: \`${t.group}\`` : "",
      ...["readOnlyHint", "destructiveHint", "idempotentHint", "openWorldHint"]
        .filter((h) => typeof t.annotations[h] === "boolean")
        .map((h) => `${h}: ${t.annotations[h]}`),
    ].filter(Boolean);
    if (facts.length) md.push(facts.join(" · "), "");
    md.push(t.description, "");
    if (t.parameters.length) {
      md.push(
        "| Parameter | Type | Required | Description |",
        "| --- | --- | --- | --- |"
      );
      for (const p of t.parameters) {
        const enumText = p.enum
          ? ` One of: ${p.enum.map((v) => `\`${String(v)}\``).join(", ")}.`
          : "";
        md.push(
          `| \`${p.name}\` | ${cell(p.type)} | ${p.required ? "yes" : "no"} | ${cell(p.description)}${cell(enumText) ? ` ${cell(enumText)}` : ""} |`
        );
      }
      md.push("");
    } else {
      md.push("No parameters.", "");
    }
  }
  await emit("mcp-tools.md", md.join("\n"));
  return entries.length;
}

// ── Events ──────────────────────────────────────────────────────────────────

async function events() {
  const { OperationalEventTypes, SystemEventTypes } =
    await import("../../packages/events/src/event-types.js");
  const unified = await import("../../packages/types/src/events/unified.js");

  const catalog = Object.entries(
    OperationalEventTypes as Record<
      string,
      {
        type: string;
        label: string;
        domain: string;
        description: string;
        filterKeys?: string[];
      }
    >
  ).map(([key, e]) => ({
    key,
    type: e.type,
    label: e.label,
    domain: e.domain,
    description: e.description,
    filterKeys: e.filterKeys ?? [],
  }));
  const system = Object.entries(SystemEventTypes as Record<string, string>).map(
    ([key, type]) => ({ key, type })
  );
  const grammar = {
    pattern: "{subject}.{action}.{phase}",
    subjectTypes: unified.SUBJECT_TYPES,
    actions: unified.EVENT_ACTIONS,
    phases: unified.EVENT_PHASES,
    domainVerbSubjectTypes: unified.DOMAIN_SUBJECT_TYPES,
    connectorSubjectTypes: unified.CONNECTOR_SUBJECT_TYPES,
    messageAliasPatterns: unified.MESSAGE_ALIAS_PATTERNS,
    observationNamespaces: unified.OBSERVATION_NAMESPACES,
  };

  await emit(
    "events.json",
    JSON.stringify({
      $comment: GENERATED_BY,
      source: [
        "packages/events/src/event-types.ts (OperationalEventTypes, SystemEventTypes)",
        "packages/types/src/events/unified.ts (naming grammar)",
      ],
      eventCount: catalog.length,
      events: catalog,
      systemEvents: system,
      grammar,
    })
  );

  const list = (xs: readonly string[]) => xs.map((x) => `\`${x}\``).join(", ");
  const md: string[] = [
    `<!-- ${GENERATED_BY} -->`,
    "",
    "# Events",
    "",
    `The pod's event catalog: the ${catalog.length} event types an automation trigger can name.`,
    "",
    "## Catalog",
    "",
  ];
  const domains = [...new Set(catalog.map((e) => e.domain))];
  for (const d of domains) {
    md.push(`### ${d}`, "");
    md.push(
      "| Event type | Name | Description | Filter keys |",
      "| --- | --- | --- | --- |"
    );
    for (const e of catalog.filter((x) => x.domain === d))
      md.push(
        `| \`${e.type}\` | ${cell(e.label)} | ${cell(e.description)} | ${e.filterKeys.map((k) => `\`${cell(k)}\``).join(", ")} |`
      );
    md.push("");
  }
  md.push(
    "## System events",
    "",
    ...system.map((s) => `- \`${s.type}\``),
    "",
    "## Naming grammar",
    "",
    `Event types follow \`${grammar.pattern}\`.`,
    "",
    `- Subjects (record changes): ${list(grammar.subjectTypes)}`,
    `- Actions: ${list(grammar.actions)}`,
    `- Phases: ${list(grammar.phases)}`,
    `- Subjects whose action is a domain verb: ${list(grammar.domainVerbSubjectTypes)}`,
    `- Connector and system families: ${list(grammar.connectorSubjectTypes)}`,
    `- Message alias patterns: ${list(grammar.messageAliasPatterns)}`,
    `- Observation namespaces: ${list(grammar.observationNamespaces)}`,
    "",
    "Automation trigger patterns accept an exact type (`entity.create.completed`), an action wildcard (`entity.create.*`) or a subject wildcard (`entity.*`).",
    ""
  );
  await emit("events.md", md.join("\n"));
  return catalog.length;
}

// ── Hub OpenAPI ─────────────────────────────────────────────────────────────

async function hubOpenApi() {
  const { hubProtocolRestApp: app } =
    await import("../../packages/api/src/routers/hub-protocol-rest.js");
  // `openAPIRegistry.definitions` is a getter that returns a fresh copy, so the
  // set the generator reads is swapped through the registry's own array.
  type Definition = { type: string; route?: { method: string; path: string } };
  const registry = app.openAPIRegistry as unknown as {
    parents?: unknown[];
    _definitions: Definition[];
  };
  if (registry.parents?.length)
    throw new Error("hub OpenAPI registry has parent registries; not handled");
  const all = registry._definitions;
  const generate = (defs: Definition[]) => {
    registry._definitions = defs;
    try {
      return app.getOpenAPI31Document({
        openapi: "3.1.0",
        info: { title: "probe", version: "0" },
      });
    } finally {
      registry._definitions = all;
    }
  };

  // An operation whose schema the generator cannot express makes the whole
  // document fail (the live route answers 500). Find those, leave them out, and
  // say so in the document rather than publish nothing.
  const omitted: Array<{ method: string; path: string; reason: string }> = [];
  const kept = all.filter((d) => {
    try {
      generate([d]);
      return true;
    } catch (err) {
      omitted.push({
        method: d.route?.method ?? d.type,
        path: d.route?.path ?? "",
        reason: err instanceof Error ? err.message : String(err),
      });
      return false;
    }
  });

  // The document itself comes from the real route, so its info, servers and
  // security are the ones hub-protocol-rest.ts declares.
  let doc: Record<string, unknown>;
  registry._definitions = kept;
  try {
    const res = await app.request("/openapi.json");
    if (res.status !== 200)
      throw new Error(
        `GET /openapi.json answered ${res.status}: ${await res.text()}`
      );
    doc = (await res.json()) as Record<string, unknown>;
  } finally {
    registry._definitions = all;
  }

  const out = {
    ...doc,
    "x-synap-generated": {
      by: "scripts/docs/gen-reference.ts",
      from: "GET /api/hub/openapi.json (packages/api/src/routers/hub-protocol-rest.ts)",
      omittedOperations: omitted,
    },
  };
  await emit("hub-openapi.json", JSON.stringify(out));
  return {
    paths: Object.keys((doc.paths as object) ?? {}).length,
    omitted: omitted.length,
  };
}

// ── main ────────────────────────────────────────────────────────────────────

const toolCount = await mcpTools();
const eventCount = await events();
const api = await hubOpenApi();
const summary = `${toolCount} MCP tools, ${eventCount} events, ${api.paths} OpenAPI paths (${api.omitted} operations omitted)`;

if (CHECK) {
  const stale = outputs.filter(
    ({ file, content }) =>
      !existsSync(file) || readFileSync(file, "utf8") !== content
  );
  if (stale.length) {
    console.error(
      `Stale reference: ${stale.map((o) => relative(ROOT, o.file)).join(", ")}`
    );
    console.error(
      "The source changed since these were generated. Run `pnpm docs:reference` and commit the result."
    );
    process.exit(1);
  }
  console.log(`Reference is up to date: ${summary}.`);
} else {
  mkdirSync(OUT_DIR, { recursive: true });
  for (const { file, content } of outputs) writeFileSync(file, content);
  console.log(`Wrote ${outputs.length} files to docs/reference: ${summary}.`);
}
// The imported API leaves timers and a lazy pool behind; nothing is pending.
process.exit(0);
