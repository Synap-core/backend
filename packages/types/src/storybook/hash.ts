/**
 * A content mark for "did this record change": a stable JSON serialisation
 * (object keys sorted, `undefined` dropped) hashed to 53 bits (cyrb53). Pure
 * and synchronous, so it runs the same in the pod, a browser and a build
 * script. NOT a cryptographic hash: it only answers "same input as last
 * time?", and the sync only ever compares two of them for equality.
 */

/** JSON with object keys sorted at every depth, so equal data gives equal text. */
export function stableStringify(value: unknown): string {
  if (value === null || typeof value !== "object") {
    return JSON.stringify(value) ?? "null";
  }
  if (Array.isArray(value)) {
    return `[${value.map((v) => (v === undefined ? "null" : stableStringify(v))).join(",")}]`;
  }
  const obj = value as Record<string, unknown>;
  const parts: string[] = [];
  for (const key of Object.keys(obj).sort()) {
    const v = obj[key];
    if (v === undefined) continue;
    parts.push(`${JSON.stringify(key)}:${stableStringify(v)}`);
  }
  return `{${parts.join(",")}}`;
}

function cyrb53(text: string): number {
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < text.length; i++) {
    const ch = text.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507);
  h1 ^= Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507);
  h2 ^= Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return 4294967296 * (2097151 & h2) + (h1 >>> 0);
}

/** `c53-<14 hex>`: the content mark of a value. Equal data, equal mark. */
export function contentHash(value: unknown): string {
  return `c53-${cyrb53(stableStringify(value)).toString(16).padStart(14, "0")}`;
}
