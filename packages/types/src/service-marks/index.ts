/**
 * Service marks — the ONE registry for third-party service identity.
 *
 * `{ id → name, mark (SVG path), brand colour }` for the services Synap
 * connects to or imports from (Telegram, WhatsApp, Gmail, GitHub, …). Every
 * surface that shows WHICH service something came from resolves it here — a
 * chat header chip, a connector card, an integrations list — so a user
 * recognises a service by its real mark instead of recalling which generic
 * glyph a given screen chose for it. Never hand-write a service → icon/colour
 * /label map at a call site; add a row here.
 *
 * CONTENT, NOT CHROME. A brand mark and its colour belong to the brand owner,
 * like a tldraw shape colour belongs to the canvas content: they are EXEMPT
 * from the tokens-only rule (`.claude/rules/ui-rules.md` "Third-party service
 * marks"). Everything AROUND a mark — the chip, the row, the label — tokenizes
 * as normal.
 *
 * SOURCE + LICENCE. Paths and colours are vendored (only the marks we use,
 * a few KB) from Simple Icons v16.32.0 (https://simpleicons.org), which is
 * released under CC0-1.0. Simple Icons' disclaimer applies: CC0 covers the
 * project, not the trademarks — each mark is used only to refer to that
 * service, per its owner's guidelines. Brands whose owners asked Simple Icons
 * to REMOVE their mark (Slack, LinkedIn, Microsoft Outlook, OpenAI — absent
 * from v16.32.0) carry `path: null`: we do not vendor a withdrawn mark from an
 * older release. They render the neutral glyph tinted with the brand colour
 * until an owner-supplied asset is licensed.
 *
 * Pure + dependency-free (only the vocabulary door for the unknown-id name) —
 * safe in browser, Electron, React Native, Node and CLI. Renderers:
 * `ServiceMark` in `@synap-core/object-registry/react` (web) and relay's
 * `src/components/ServiceMark.tsx` (native); both draw exactly what
 * {@link resolveServiceMark} returns and decide nothing themselves.
 */

