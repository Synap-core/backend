export interface ServiceMarkDef {
  /** Human name, exactly as the brand writes it. */
  readonly name: string;
  /**
   * The mark: ONE SVG path on a 24×24 viewBox, drawn as a fill. `null` = no
   * mark we may vendor (owner-withdrawn brand, or not a brand at all) — the
   * neutral {@link GENERIC_SERVICE_PATH} is drawn instead.
   */
  readonly path: string | null;
  /** Official brand colour (`#RRGGBB`). Omitted only with `inkMark`. */
  readonly hex?: `#${string}`;
  /**
   * The brand's own colour is black/white (GitHub, Notion, X) — its guidelines
   * render the mark in the surrounding ink, so the full-colour variant uses
   * `currentColor` too (a #000 mark would vanish on a dark ground).
   */
  readonly inkMark?: true;
  /** Other ids the same service arrives under (connector keys, legacy names). */
  readonly aliases?: readonly string[];
}

